------ Q21. Month-over-month revenue change using LAG

WITH monthly_sales AS (
    SELECT
        CONVERT(VARCHAR(7), o.order_date, 120) AS sales_month,
        SUM(
            oi.quantity * oi.unit_price *
            (1 - oi.discount_pct / 100.0)
        ) AS revenue
    FROM orders o
    JOIN order_items oi
        ON oi.order_id = o.order_id
    WHERE o.status IN ('Completed', 'Shipped')
    GROUP BY CONVERT(VARCHAR(7), o.order_date, 120)
),
comparison AS (
    SELECT
        sales_month,
        revenue,
        LAG(revenue) OVER (ORDER BY sales_month) AS previous_month_revenue
    FROM monthly_sales
)
SELECT
    sales_month,
    ROUND(revenue, 2) AS revenue,
    ROUND(previous_month_revenue, 2) AS previous_month_revenue,
    ROUND(revenue - previous_month_revenue, 2) AS change_amount,
    ROUND(
        100.0 * (revenue - previous_month_revenue)
        / NULLIF(previous_month_revenue, 0),
        2
    ) AS change_pct
FROM comparison
ORDER BY sales_month;

